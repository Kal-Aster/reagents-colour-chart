#!/usr/bin/env python3
"""Recupera le descrizioni dei reagenti.

Per ogni reagente prende un passaggio in inglese, cosi' com'e', da una fonte
con una licenza che lo permette: la sua voce su Wikipedia o un articolo open
access, letto da Europe PMC. Lo scrive in data/descriptions.js, uno script
semplice perche' la pagina si apre anche dal disco, dove fetch() non puo'
leggere un file locale:

    /* licenza */
    window.DESCRIPTIONS = {
      "license": "CC BY-SA 4.0",
      "sources": { "<id>": { "label", "year", "url", "license" } },
      "locales": { "<lingua>": { "reagents": { "<nome>": { "description": "...",
          "source": { "href": "...", "translated": false, "main": "<id>" } } } } } }

Le fonti in "sources" sono quelle principali, con la loro licenza; "href" e'
il punto preciso da cui viene il passaggio.

Le altre lingue sono traduzioni fatte a mano dello stesso testo, con
"translated": true e la stessa fonte. Lo script le lascia come sono: dice
quali mancano e quali vanno riviste perche' l'originale e' cambiato
dall'ultima volta.

    python3 tools/fetch_descriptions.py
"""
from __future__ import annotations

import html
import json
import re
import time
from datetime import datetime, timezone
import urllib.error
import urllib.parse
import urllib.request
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REAGENTS = ROOT / "data" / "reagents.json"
OUT = ROOT / "data" / "descriptions.js"
PREFIX = "window.DESCRIPTIONS = "
# La licenza del file: i passaggi di Wikipedia e le loro traduzioni restano
# CC BY-SA (share-alike), e un testo CC BY puo' stare in un'opera CC BY-SA.
LICENSE = "CC BY-SA 4.0"
HEADER = """\
/* Reagent descriptions, as written by their sources, and their translations.
 *
 * Licence: CC BY-SA 4.0 (https://creativecommons.org/licenses/by-sa/4.0/).
 * The passages come from the sources in "sources", each under its own
 * licence; every description links to the exact place it was taken from
 * and says whether it was translated.
 *
 * Generated by tools/fetch_descriptions.py. */
"""
LANGUAGE = "en"
API = f"https://{LANGUAGE}.wikipedia.org/w/api.php"
USER_AGENT = "reagent-color-chart/1.0 (tools/fetch_descriptions.py)"
EUROPE_PMC = "https://www.ebi.ac.uk/europepmc/webservices/rest/{}/fullTextXML"

WIKIPEDIA = "WP"
# le fonti principali; l'anno di Wikipedia e' quello in cui e' stata letta
SOURCES = {
    WIKIPEDIA: {"label": "Wikipedia", "url": f"https://{LANGUAGE}.wikipedia.org",
                "license": "CC BY-SA 4.0"},
    "Houtzager2024": {
        "label": "Houtzager et al., Analytical and Bioanalytical Chemistry",
        "year": 2024,
        "url": "https://doi.org/10.1007/s00216-023-05013-x",
        "license": "CC BY 4.0",
    },
}

# reagente -> (voce, sezione, inizi dei blocchi). Senza sezione e' l'
# introduzione della voce; senza inizi e' il primo paragrafo. Un blocco e' un
# paragrafo o un punto di un elenco: piu' inizi danno blocchi consecutivi,
# uniti, quando uno da solo non si capisce.
ARTICLES = {
    "Marquis": ("Marquis reagent", None, None),
    "Mecke": ("Mecke reagent", None, None),
    "Mandelin": ("Mandelin reagent", None, None),
    "Froehde": ("Froehde reagent", None, None),
    "Liebermann": ("Liebermann reagent", None, None),
    "Simon's": ("Simon's reagent", None, None),
    "Ehrlich": ("Ehrlich's reagent", None, None),
    # il punto dell'elenco confronta i colori con quelli di Ehrlich: la frase
    # che introduce l'elenco dice con che cosa
    "Hofmann": ("Ehrlich's reagent", "Preparation",
                ["The Ehrlich reagent is similar", "The van Urk reagent"]),
    "Gallic": ("Gallic acid reagent", None, None),
    "Robadope": ("Simon's reagent", "Chemistry", ["Acetaldehyde can be replaced"]),
    "Morris": ("Cobalt(II) thiocyanate", "Cobalt thiocyanate test", None),
    "Zimmermann": ("Zimmermann reagent", None, None),
    "Scott": ("Cobalt(II) thiocyanate", "Scott's test", None),
    "Folin": ("Folin's reagent", None, None),
}

# reagente -> (fonte, PMCID, inizi delle frasi): frasi consecutive dello
# stesso paragrafo di un articolo open access. Il 4-AP non ha una voce su
# Wikipedia.
PAPERS = {
    "Cannabis (4-AP)": ("Houtzager2024", "PMC10758360",
                        ["Another colorimetric test", "The 4-AP reaction provides"]),
}


class Blocks(HTMLParser):
    """Il testo dei paragrafi e dei punti degli elenchi di una sezione, in
    ordine, senza note e senza stili: (tag, testo)."""

    SKIPPED = {"sup", "style", "script"}
    BLOCKS = {"p", "li"}

    def __init__(self) -> None:
        super().__init__()
        self.blocks: list[tuple[str, str]] = []
        self.current: list[str] | None = None
        self.current_tag: str | None = None
        self.current_depth = 0
        self.skipped_depth = 0

    def handle_starttag(self, tag, attributes):
        if self.skipped_depth or tag in self.SKIPPED:
            self.skipped_depth += 1
        elif tag in self.BLOCKS and self.current is None:
            self.current, self.current_tag, self.current_depth = [], tag, 1
        elif tag == self.current_tag:
            # un elenco dentro un punto resta nel punto
            self.current_depth += 1

    def handle_endtag(self, tag):
        if self.skipped_depth:
            self.skipped_depth -= 1
        elif tag == self.current_tag and self.current is not None:
            self.current_depth -= 1
            if self.current_depth:
                return
            text = re.sub(r"\s+", " ", "".join(self.current)).strip()
            if text:
                self.blocks.append((tag, text))
            self.current, self.current_tag = None, None

    def handle_data(self, data):
        if self.current is not None and not self.skipped_depth:
            self.current.append(data)


def download(url: str) -> bytes:
    """Una richiesta alla volta: Wikipedia risponde 429 a chi ne fa troppe
    di fila, e dice quanto aspettare."""
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    for attempt in range(5):
        time.sleep(1)
        try:
            with urllib.request.urlopen(request, timeout=30) as response:
                return response.read()
        except urllib.error.HTTPError as error:
            if error.code != 429:
                raise
            time.sleep(int(error.headers.get("Retry-After", 10 * (attempt + 1))))
    raise RuntimeError(f"troppe richieste: {url}")


def query(**parameters) -> dict:
    parameters.update(format="json", formatversion="2")
    return json.loads(download(API + "?" + urllib.parse.urlencode(parameters)))


def section_index(title: str, section: str | None) -> tuple[int, str | None]:
    if section is None:
        return 0, None
    sections = query(action="parse", page=title, prop="sections")["parse"]["sections"]
    for entry in sections:
        if entry["line"] == section:
            return int(entry["index"]), entry["anchor"]
    raise LookupError(f"{title}: nessuna sezione {section!r}")


def fetch_wikipedia(title: str, section: str | None, starts: list[str] | None) -> dict:
    index, anchor = section_index(title, section)
    parsed = query(action="parse", page=title, section=index, prop="text",
                   disableeditsection=1, redirects=1)["parse"]
    parser = Blocks()
    parser.feed(parsed["text"])
    if starts is None:
        texts = [next((text for tag, text in parser.blocks if tag == "p"), None)]
    else:
        texts = [next((text for tag, text in parser.blocks if text.startswith(start)), None)
                 for start in starts]
    if None in texts:
        raise LookupError(f"{title}: blocchi non trovati {starts!r}")
    href = (f"https://{LANGUAGE}.wikipedia.org/wiki/"
            + urllib.parse.quote(parsed["title"].replace(" ", "_"), safe="'()"))
    if anchor:
        href += "#" + anchor
    return {"description": " ".join(texts),
            "source": {"href": href, "translated": False, "main": WIKIPEDIA}}


def fetch_paper(main: str, pmcid: str, starts: list[str]) -> dict:
    xml = download(EUROPE_PMC.format(pmcid)).decode("utf-8")
    # i rimandi alla bibliografia, "[10]" o "[3, 4]", restano nell'articolo
    xml = re.sub(r"\s*\[(?:<xref[^>]*>[^<]*</xref>[\s,–-]*)+\]", "", xml)
    paragraphs = [re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", "", paragraph))).strip()
                  for paragraph in re.findall(r"<p\b[^>]*>(.*?)</p>", xml, re.S)]
    sentences = []
    for start in starts:
        paragraph = next((paragraph for paragraph in paragraphs if start in paragraph), None)
        if paragraph is None:
            raise LookupError(f"{pmcid}: nessuna frase {start!r}")
        rest = paragraph[paragraph.index(start):]
        end = re.search(r"\.(\s|$)", rest)
        sentences.append(rest[:end.end()].strip() if end else rest)
    return {"description": " ".join(sentences),
            "source": {"href": SOURCES[main]["url"], "translated": False, "main": main}}


def read_descriptions() -> dict:
    if not OUT.exists():
        return {}
    text = OUT.read_text(encoding="utf-8")
    data = text[text.index(PREFIX) + len(PREFIX):].strip().removesuffix(";")
    return json.loads(data)


def check_translations(originals: dict, previous: dict, locales: dict) -> None:
    """Le traduzioni che mancano e quelle di un originale che e' cambiato:
    il confronto e' con il testo inglese scritto l'ultima volta."""
    for language, content in locales.items():
        if language == LANGUAGE:
            continue
        translations = content["reagents"]
        for name, original in originals.items():
            translation = translations.get(name)
            if translation is None:
                print(f"{language}: {name} da tradurre")
            elif (translation["source"] != {**original["source"], "translated": True}
                  or previous.get(name, {}).get("description") != original["description"]):
                print(f"{language}: {name} da rivedere, l'originale e' cambiato")


def main() -> None:
    reagents = json.loads(REAGENTS.read_text(encoding="utf-8"))["reagents"]
    originals = {}
    for reagent in reagents:
        name = reagent["name"]
        if name in ARTICLES:
            originals[name] = fetch_wikipedia(*ARTICLES[name])
        elif name in PAPERS:
            originals[name] = fetch_paper(*PAPERS[name])
        else:
            print(f"{name}: nessuna fonte")

    sources = dict(SOURCES)
    sources[WIKIPEDIA] = dict(SOURCES[WIKIPEDIA], year=datetime.now(timezone.utc).year)
    previous_locales = read_descriptions().get("locales", {})
    previous = previous_locales.get(LANGUAGE, {}).get("reagents", {})
    # l'inglese per primo; le traduzioni restano come sono
    locales = {LANGUAGE: {"reagents": originals}}
    for language, content in previous_locales.items():
        locales.setdefault(language, content)
    descriptions = {"license": LICENSE, "sources": sources, "locales": locales}
    OUT.write_text(HEADER + PREFIX + json.dumps(descriptions, indent=1, ensure_ascii=False)
                   + ";\n", encoding="utf-8")
    print(f"scritto {OUT} ({len(originals)} reagenti, lingue {', '.join(locales)})")
    check_translations(originals, previous, locales)


if __name__ == "__main__":
    main()
